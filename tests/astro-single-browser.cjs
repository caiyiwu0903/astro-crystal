const { chromium, webkit } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = process.env.CARDS_TEST_WEBKIT ? await webkit.launch({ headless: true }) : await chromium.launch({ channel: 'chrome', headless: true });
  const errors = [], external = [];
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => {
    if (!route.request().url().startsWith('http://127.0.0.1:4174/')) { external.push(route.request().url()); return route.abort(); }
    return route.continue();
  });
  await page.goto('http://127.0.0.1:4174/astro-cards.html#single');
  await page.locator('#single-submit:enabled').waitFor();
  assert.match(await page.locator('#single-service').innerText(), /未呼叫 AI/);
  for (const width of [375, 390, 430]) {
    await page.setViewportSize({ width, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `overflow ${width}`);
  }
  await page.locator('#single-input').fill('字'.repeat(55));
  assert.equal((await page.locator('#single-input').inputValue()).length, 50);
  await page.locator('#single-input').fill('想換工作，但不知道下一步');
  await page.locator('#single-submit').click();
  assert.ok(await page.locator('#single-followup').isVisible());
  await page.locator('#single-submit').click();
  assert.match(await page.locator('#single-status').innerText(), /選一個/);
  await page.locator('[name="single-choice"][value="direction"]').check();
  await page.locator('#single-submit').click();
  await page.locator('#single-result').waitFor({ state: 'visible' });
  assert.match(await page.locator('#single-focus').innerText(), /不知道下一步/);
  assert.match(await page.locator('#single-source').innerText(), /未呼叫 AI/);
  assert.equal(await page.locator('#single-card .astro-card').count(), 1);
  await page.screenshot({ path: 'tmp/astro-single-preview.png', fullPage: true });
  await page.locator('#single-reset').click();
  await page.locator('#single-input').fill('面試自我介紹怎麼準備？');
  await page.locator('#single-submit').click();
  await page.locator('#single-result').waitFor({ state: 'visible' });
  assert.ok(await page.locator('#single-focus').isHidden());
  await page.locator('#single-reset').click();
  await page.locator('#single-input').fill('我喜歡同事，怎麼辦？');
  await page.locator('#single-submit').click();
  assert.match(await page.locator('#single-followup-prompt').innerText(), /喜歡/);
  await page.locator('#single-edit').click();
  assert.equal(await page.locator('#single-input').getAttribute('readonly'), null);
  await page.locator('#single-submit').click();
  await page.locator('#single-skip').click();
  await page.locator('#single-result').waitFor({ state: 'visible' });
  assert.ok(await page.locator('#single-focus').isHidden());
  await page.locator('#single-reset').click();
  await page.locator('#single-input').fill('面試自我介紹怎麼準備？');
  await page.locator('#single-submit').click();
  await page.locator('#single-result').waitFor({ state: 'visible' });
  await page.goto('http://127.0.0.1:4174/astro-cards.html?mode=love&what=P04&how=S06&where=H07');
  assert.ok(await page.locator('#cards-three-panel').isVisible());
  assert.equal(await page.locator('#cards-spread .astro-card').count(), 3);
  await page.locator('#cards-draw').click();
  await page.locator('#cards-draw:enabled').waitFor();
  assert.match(await page.locator('[data-cards-count]').first().innerText(), /本機預覽不計入/);
  await page.locator('[name="experience"][value="single"]').check();
  await page.locator('#single-submit:enabled').waitFor();
  await page.route('**/api/astro-single', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'AI 暫時無法回覆，請稍後再試。' }) }));
  await page.locator('#single-input').fill('今天怎麼安排？');
  await page.locator('#single-submit').click();
  await page.locator('#single-submit:enabled').waitFor();
  assert.match(await page.locator('#single-status').innerText(), /暫時無法回覆/);
  assert.ok(await page.locator('#single-result').isHidden());
  assert.equal(external.filter(url => url.includes('supabase')).length, 0);
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: mobile widths, question limit, follow-up/select/skip/edit, single result, three-card URL/draw, no stats requests or JS errors.');
})().catch(error => { console.error(error); process.exit(1); });
